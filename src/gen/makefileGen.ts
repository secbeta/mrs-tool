import * as path from 'path';
import type { MrsProject } from '../project/projectModel';
import type { MrsInstallation } from '../locator/mrsInstallation';
import { toPosix } from '../util/fsx';

/**
 * Renders the generated Makefile. Design mirrors MRS defaults:
 * recursive source discovery under configured dirs, prebuilt .a archives
 * wrapped in --start-group/--end-group, dep files, obj/ output convention.
 */
export function renderMakefile(proj: MrsProject, inst: MrsInstallation): string {
  const b = proj.build;
  const toolchain = inst.toolchains.resolve(proj.mcu.toolchainName);
  const binDir = toolchain ? toPosix(toolchain.binDir) : '<TOOLCHAIN BIN NOT RESOLVED>';
  const prefix = toolchain?.prefix ?? '';
  const isa = inst.chipDb.findSeries(proj.mcu.series)?.isa;
  const cpuFlags = isa
    ? isa.cpuFlags
    : proj.mcu.toolchainType === 'ARM'
      ? '-mcpu=cortex-m3 -mthumb'
      : '-march=rv32imac -mabi=ilp32';

  const q = (s: string) => s.replace(/ /g, '\\ ');

  const lines: string[] = [];
  lines.push('# ============================================================================');
  lines.push('#  Makefile — generated by MRS Toolbox. DO NOT EDIT.');
  lines.push('#  Edit .mrs-project.json and run "MRS Toolbox: Generate Build Files".');
  lines.push(`#  Project : ${b.targetName}    Series : ${proj.mcu.series}    MCU : ${proj.mcu.mcuId}`);
  lines.push(`#  Toolchain: ${proj.mcu.toolchainType} / ${proj.mcu.toolchainName}  (${prefix})`);
  lines.push('#  Targets: make [all] | make clean | make rebuild   (CONFIG=debug|release)');
  lines.push(
    process.platform === 'win32'
      ? '#  NOTE: run through the extension, or have MRS2 Make\\bin (sh.exe) on PATH.'
      : '#  NOTE: run through the extension, or have MRS2 Make/bin and the toolchain bin on PATH.',
  );
  lines.push('# ============================================================================');
  lines.push('');
  lines.push(`TARGET        := ${b.targetName}`);
  lines.push('CONFIG        ?= debug');
  lines.push(`BUILD_DIR     := ${b.outputDir}`);
  lines.push('');
  lines.push('# ---- Toolchain (from MounRiver Studio 2) ----------------------------------');
  lines.push(`TOOLCHAIN_BIN := ${q(binDir)}`);
  lines.push(`PREFIX        := $(TOOLCHAIN_BIN)/${prefix}`);
  lines.push('CC            := $(PREFIX)gcc');
  lines.push('CXX           := $(PREFIX)g++');
  lines.push('LD            := $(PREFIX)gcc');
  lines.push('OBJCOPY       := $(PREFIX)objcopy');
  lines.push('OBJDUMP       := $(PREFIX)objdump');
  lines.push('SIZE          := $(PREFIX)size');
  lines.push('');
  lines.push(`ARCH_TYPE     := ${proj.mcu.toolchainType === 'ARM' ? 'arm' : 'riscv'}`);
  lines.push(`CPUFLAGS      := ${cpuFlags}`);
  lines.push('');
  lines.push('# ---- Sources (recursive scan) ---------------------------------------------');
  lines.push(`SRC_DIRS      := ${b.srcDirs.join(' ')}`);
  lines.push(b.libDirs.length ? `LIB_DIRS      := ${b.libDirs.join(' ')}` : 'LIB_DIRS      :=');
  lines.push(`LINKER_SCRIPT := ${b.linkerScript}`);
  lines.push('');
  lines.push('rwildcard     = $(foreach d,$(wildcard $(1:=/*)),$(call rwildcard,$(d),$(2)) $(filter $(2),$d))');
  // NB: make filter patterns need an explicit % — "*" alone is a literal.
  lines.push('ALL_FILES     := $(call rwildcard,$(SRC_DIRS),%)');
  lines.push('C_SOURCES     := $(filter %.c,$(ALL_FILES))');
  lines.push('CXX_SOURCES   := $(filter %.cpp %.cc %.cxx,$(ALL_FILES))');
  lines.push('ASM_UPPER     := $(filter %.S,$(ALL_FILES))');
  lines.push('ASM_LOWER     := $(filter %.s,$(ALL_FILES))');
  lines.push('PREBUILT_LIBS := $(call rwildcard,$(LIB_DIRS),%.a)');
  if (b.excludedPaths?.length) {
    // Mirrors the Eclipse sourceEntries `excluding=…` list: each entry drops
    // the exact file and everything under it as a directory.
    lines.push('# ---- Excluded from build (mirrors the example project settings) -------------');
    lines.push(`EXCLUDED      := ${b.excludedPaths.join(' ')}`);
    lines.push('EXCLUDE_PATS  := $(EXCLUDED) $(EXCLUDED:%=%/%)');
    lines.push('C_SOURCES     := $(filter-out $(EXCLUDE_PATS),$(C_SOURCES))');
    lines.push('CXX_SOURCES   := $(filter-out $(EXCLUDE_PATS),$(CXX_SOURCES))');
    lines.push('ASM_UPPER     := $(filter-out $(EXCLUDE_PATS),$(ASM_UPPER))');
    lines.push('ASM_LOWER     := $(filter-out $(EXCLUDE_PATS),$(ASM_LOWER))');
  }
  lines.push('');
  const extraInc = b.extraIncludes.map((i) => `-I${q(i)}`).join(' ');
  lines.push(
    'INCLUDES      := -I. $(foreach d,$(sort $(dir $(call rwildcard,$(SRC_DIRS) $(LIB_DIRS),%.h))),-I$(d))' +
      (extraInc ? ' ' + extraInc : ''),
  );
  lines.push(`DEFS          := ${b.defines.map((d) => `-D${d}`).join(' ')}`);
  lines.push('');
  lines.push('# ---- Flags (mirror MRS defaults) ------------------------------------------');
  lines.push('ifeq ($(CONFIG),release)');
  lines.push(`OPT           := ${b.releaseOpt} -g`);
  lines.push('else');
  lines.push(`OPT           := ${b.debugOpt} -g3`);
  lines.push('endif');
  lines.push('COMMON        := $(OPT) $(CPUFLAGS) -fmessage-length=0 -fsigned-char \\');
  lines.push('                 -ffunction-sections -fdata-sections -fno-common');
  lines.push(`CFLAGS        := $(COMMON) -std=${b.cStd}${b.cFlagsExtra.length ? ' ' + b.cFlagsExtra.join(' ') : ''}`);
  lines.push(`CXXFLAGS      := $(COMMON) -std=${b.cxxStd}${b.cxxFlagsExtra.length ? ' ' + b.cxxFlagsExtra.join(' ') : ''}`);
  lines.push(`ASFLAGS       := $(COMMON) -x assembler-with-cpp${b.asFlagsExtra.length ? ' ' + b.asFlagsExtra.join(' ') : ''}`);
  lines.push('LDFLAGS       := $(CPUFLAGS) -T $(LINKER_SCRIPT) -nostartfiles \\');
  lines.push('                 --specs=nano.specs --specs=nosys.specs \\');
  lines.push('                 -Wl,--gc-sections -Wl,--print-memory-usage \\');
  lines.push('                 -Wl,-Map=$(BUILD_DIR)/$(TARGET).map \\');
  lines.push(
    '                 -Wl,--start-group $(PREBUILT_LIBS) -Wl,--end-group' +
      (b.ldFlagsExtra.length ? ' ' + b.ldFlagsExtra.join(' ') : ''),
  );
  lines.push('');
  lines.push('OBJECTS       := $(C_SOURCES:%.c=$(BUILD_DIR)/%.o) \\');
  lines.push('                 $(CXX_SOURCES:%.cpp=$(BUILD_DIR)/%.o) \\');
  lines.push('                 $(ASM_UPPER:%.S=$(BUILD_DIR)/%.o) \\');
  lines.push('                 $(ASM_LOWER:%.s=$(BUILD_DIR)/%.o)');
  lines.push('VPATH         := $(SRC_DIRS)');
  lines.push('');
  lines.push('.DEFAULT_GOAL := all');
  lines.push('.PHONY        : all clean rebuild dirs');
  lines.push('');
  const outputs = [
    `$(BUILD_DIR)/$(TARGET).elf`,
    b.generateHex ? `$(BUILD_DIR)/$(TARGET).hex` : '',
    b.generateBin ? `$(BUILD_DIR)/$(TARGET).bin` : '',
    b.generateListing ? `$(BUILD_DIR)/$(TARGET).lst` : '',
  ]
    .filter(Boolean)
    .join(' ');
  lines.push(`all: ${outputs}`);
  lines.push('');
  lines.push('$(BUILD_DIR)/$(TARGET).elf: $(OBJECTS) $(LINKER_SCRIPT) | dirs');
  lines.push('\t@echo "== LD    $@"');
  lines.push('\t$(CC) $(OBJECTS) $(LDFLAGS) -o $@');
  lines.push('\t@$(SIZE) $@');
  lines.push('');
  lines.push('$(BUILD_DIR)/%.o: %.c | dirs');
  lines.push('\t@echo "== CC    $<"');
  lines.push('\t$(CC) $(CFLAGS) $(DEFS) $(INCLUDES) -MMD -MP -c $< -o $@');
  lines.push('');
  lines.push('$(BUILD_DIR)/%.o: %.cpp | dirs');
  lines.push('\t@echo "== CXX   $<"');
  lines.push('\t$(CXX) $(CXXFLAGS) $(DEFS) $(INCLUDES) -MMD -MP -c $< -o $@');
  lines.push('');
  lines.push('$(BUILD_DIR)/%.o: %.S | dirs');
  lines.push('\t@echo "== AS    $<"');
  lines.push('\t$(CC) $(ASFLAGS) $(DEFS) $(INCLUDES) -MMD -MP -c $< -o $@');
  lines.push('');
  lines.push('$(BUILD_DIR)/%.o: %.s | dirs');
  lines.push('\t@echo "== AS    $<"');
  lines.push('\t$(CC) $(ASFLAGS) $(DEFS) $(INCLUDES) -MMD -MP -c $< -o $@');
  lines.push('');
  if (b.generateHex) {
    lines.push('$(BUILD_DIR)/$(TARGET).hex: $(BUILD_DIR)/$(TARGET).elf');
    lines.push('\t$(OBJCOPY) -O ihex $< $@');
    lines.push('');
  }
  if (b.generateBin) {
    lines.push('$(BUILD_DIR)/$(TARGET).bin: $(BUILD_DIR)/$(TARGET).elf');
    lines.push('\t$(OBJCOPY) -O binary -S $< $@');
    lines.push('');
  }
  if (b.generateListing) {
    lines.push('$(BUILD_DIR)/$(TARGET).lst: $(BUILD_DIR)/$(TARGET).elf');
    lines.push('\t$(OBJDUMP) -h -S -l -x -w -C $< > $@');
    lines.push('');
  }
  lines.push('dirs:');
  lines.push('\t@mkdir -p $(sort $(dir $(OBJECTS)) $(BUILD_DIR))');
  lines.push('');
  lines.push('clean:');
  lines.push('\trm -rf $(BUILD_DIR)');
  lines.push('');
  // 递归串行：`rebuild: clean all` 在 -j 下两前置并行，all 会用删除前的旧
  // 时间戳判定"无事可做"，clean 再把 obj/ 删光 → 空产物却退出 0（实测竞态）。
  lines.push('rebuild:');
  lines.push('\t+$(MAKE) clean');
  lines.push('\t+$(MAKE) all');
  lines.push('');
  lines.push('-include $(OBJECTS:.o=.d)');
  lines.push('');

  return lines.join('\n');
}

/** Absolute path of the flash image for a project. */
export function flashImageAbs(projRoot: string, proj: MrsProject): string {
  return path.resolve(projRoot, proj.flash.image);
}
